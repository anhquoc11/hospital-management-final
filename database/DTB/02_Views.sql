CREATE   VIEW dbo.vw_Khoa AS
SELECT 
    k.MaKhoa, 
    k.TenKhoa, 
    k.MoTa, 
    k.MaTruongKhoa, 
    ISNULL(k.TrangThai, 1) AS TrangThai,
    nv.HoTen AS TenTruongKhoa
FROM dbo.Khoa k
LEFT JOIN dbo.NhanVien nv ON k.MaTruongKhoa = nv.MaNhanVien;
GO

